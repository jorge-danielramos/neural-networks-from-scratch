"""Synthetic time series generation for Part 2 of the homework.

Signal formulas and default constants are adapted from
`SynTSBench/dataset/signal_generators.py` (generate_sine_wave,
generate_linear_signal, generate_quadratic_signal,
generate_exponential_signal, add_noise_by_snr).
"""

import re
from dataclasses import dataclass
from typing import Optional

import numpy as np

N_POINTS = 11000
TRAIN_FRAC = 0.6
VAL_FRAC = 0.2
TEST_FRAC = 0.2

BASE_DATASET_NAMES = [
    "sine_slow",
    "sine_fast",
    "linear_trend",
    "quadra_trend",
    "expo_trend",
]

# Noisy variants are generated at each of these signal-to-noise ratios (dB).
SNR_LEVELS_DB = [20.0, 0.0, -10.0]

_NOISY_NAME_RE = re.compile(r"^(?P<base>.+)_noisy_snr(?P<snr>-?\d+(?:\.\d+)?)db$")


def noisy_name(base_name: str, snr_db: float) -> str:
    """
    Args:
        base_name: one of `BASE_DATASET_NAMES`.
        snr_db: signal-to-noise ratio in decibels.

    Returns:
        the corresponding noisy dataset name, e.g. "sine_slow_noisy_snr0db".
    """
    return f"{base_name}_noisy_snr{snr_db:g}db"


def is_noisy_name(name: str) -> bool:
    """
    Args:
        name: a dataset name.

    Returns:
        True if `name` is a noisy variant (as produced by `noisy_name`).
    """
    return _NOISY_NAME_RE.match(name) is not None


ALL_DATASET_NAMES = BASE_DATASET_NAMES + [
    noisy_name(name, snr_db) for name in BASE_DATASET_NAMES for snr_db in SNR_LEVELS_DB
]

# Per-dataset default generation constants (mirrors SynTSBench defaults,
# except: sine frequencies are chosen for a clear slow/fast contrast over
# N_POINTS samples, and expo_trend's rate ("b") is scaled down from
# SynTSBench's 0.01 since that value overflows over N_POINTS=11000 steps).
DEFAULTS = {
    "sine_slow": {"amplitude": 1.0, "frequency": 1.0 / 200.0},
    "sine_fast": {"amplitude": 1.0, "frequency": 1.0 / 20.0},
    "linear_trend": {"slope": 10.0, "intercept": 0.0},
    "quadra_trend": {"a": 1.0, "b": 1.0, "c": 1.0},
    "expo_trend": {"a": 1.0, "b": 0.001},
}


def generate_sine(n: int, amplitude: float = 1.0, frequency: float = 0.5, phase: float = 0.0) -> np.ndarray:
    """
    Args:
        n: number of time steps to generate.
        amplitude: wave amplitude.
        frequency: cycles per sample (period = 1 / frequency samples).
        phase: phase offset in radians.

    Returns:
        signal: shape (n,).
    """
    x = np.arange(n)
    return amplitude * np.sin(2 * np.pi * frequency * x + phase)


def generate_linear(n: int, slope: float = 10.0, intercept: float = 0.0) -> np.ndarray:
    """
    Args:
        n: number of time steps to generate.
        slope: linear coefficient.
        intercept: constant offset.

    Returns:
        signal: shape (n,), equal to slope * x + intercept.
    """
    x = np.arange(n)
    return slope * x + intercept


def generate_quadratic(n: int, a: float = 1.0, b: float = 1.0, c: float = 1.0) -> np.ndarray:
    """
    Args:
        n: number of time steps to generate.
        a: quadratic coefficient.
        b: linear coefficient.
        c: constant offset.

    Returns:
        signal: shape (n,), equal to a * x**2 + b * x + c.
    """
    x = np.arange(n)
    return a * x**2 + b * x + c


def generate_exponential(n: int, a: float = 1.0, b: float = 0.01) -> np.ndarray:
    """
    Args:
        n: number of time steps to generate.
        a: amplitude coefficient.
        b: growth rate.

    Returns:
        signal: shape (n,), equal to a * exp(b * x) + 1.
    """
    x = np.arange(n)
    return a * np.exp(b * x) + 1


def add_noise_by_snr(values: np.ndarray, snr_db: float) -> np.ndarray:
    """
    Args:
        values: clean signal, shape (n,).
        snr_db: desired signal-to-noise ratio in decibels.

    Returns:
        noisy_values: shape (n,), same shape as `values`, with additive
            zero-mean Gaussian noise calibrated to the requested SNR.
    """
    signal_power = np.var(values)
    snr_linear = 10 ** (snr_db / 10)
    noise_std = np.sqrt(signal_power / snr_linear)
    noise = np.random.normal(0.0, noise_std, size=values.shape)
    return values + noise


@dataclass
class TimeSeriesDataset:
    """Generates one named synthetic time series and its train/val/test split.

    Args:
        name: dataset name, one of `ALL_DATASET_NAMES`. A name of the form
            "<base>_noisy_snr<X>db" (e.g. "sine_slow_noisy_snr0db", built by
            `noisy_name`) generates the corresponding base series with
            additive Gaussian noise at X dB (see `SNR_LEVELS_DB` for the
            levels generated by default).
        n_points: total number of time steps to generate, split
            TRAIN_FRAC / VAL_FRAC / TEST_FRAC (6:2:2) into train/val/test.
        snr_db: signal-to-noise ratio in decibels for additive Gaussian
            noise. If None, the level is taken from `name` (no noise for
            a "clean"-named dataset); pass a value explicitly to add
            noise to a "clean"-named dataset, or to override the level
            encoded in a noisy one's name.
        frequency: overrides the default frequency, for "sine_slow" /
            "sine_fast".
        slope: overrides the default slope, for "linear_trend".
        intercept: overrides the default intercept, for "linear_trend".
        a: overrides the default `a` coefficient, for "quadra_trend"
            (x**2 coefficient) or "expo_trend" (amplitude).
        b: overrides the default `b` coefficient, for "quadra_trend"
            (x coefficient) or "expo_trend" (growth rate).
        c: overrides the default `c` coefficient, for "quadra_trend"
            (constant offset).
        seed: seed for the noise random generator, for reproducibility.

    Attributes (set in __post_init__):
        values: full generated series (noisy, if `name` is a noisy
            dataset), shape (n_points,).
        train: shape (round(n_points * TRAIN_FRAC),).
        val: shape (round(n_points * VAL_FRAC),).
        test: shape (n_points - len(train) - len(val),).
        clean_values: full series before any noise was added, shape
            (n_points,). Equal to `values` for non-noisy datasets.
        clean_train, clean_val, clean_test: same split as
            train/val/test, but of `clean_values`. Useful as the
            denoising target/ground truth for noisy datasets.
    """

    name: str
    n_points: int = N_POINTS
    snr_db: Optional[float] = None
    frequency: Optional[float] = None
    slope: Optional[float] = None
    intercept: Optional[float] = None
    a: Optional[float] = None
    b: Optional[float] = None
    c: Optional[float] = None
    seed: Optional[int] = None

    def __post_init__(self):
        match = _NOISY_NAME_RE.match(self.name)
        if match is not None:
            base_name, name_snr_db = match.group("base"), float(match.group("snr"))
        else:
            base_name, name_snr_db = self.name, None

        if base_name not in BASE_DATASET_NAMES:
            raise ValueError(f"Unknown dataset name {self.name!r}, expected one of {ALL_DATASET_NAMES}")

        if self.seed is not None:
            np.random.seed(self.seed)

        self.base_name = base_name
        self.clean_values = self._generate(base_name)

        snr_db = self.snr_db if self.snr_db is not None else name_snr_db
        if snr_db is not None:
            self.values = add_noise_by_snr(self.clean_values, snr_db)
        else:
            self.values = self.clean_values

        self.train, self.val, self.test = self._split(self.values)
        self.clean_train, self.clean_val, self.clean_test = self._split(self.clean_values)

    def _generate(self, base_name: str) -> np.ndarray:
        """
        Args:
            base_name: dataset name without any noisy-SNR suffix, i.e. one
                of `BASE_DATASET_NAMES`.

        Returns:
            signal: shape (self.n_points,).
        """
        defaults = DEFAULTS[base_name]
        n = self.n_points

        if base_name in ("sine_slow", "sine_fast"):
            frequency = self.frequency if self.frequency is not None else defaults["frequency"]
            return generate_sine(n, amplitude=defaults["amplitude"], frequency=frequency)

        if base_name == "linear_trend":
            slope = self.slope if self.slope is not None else defaults["slope"]
            intercept = self.intercept if self.intercept is not None else defaults["intercept"]
            return generate_linear(n, slope=slope, intercept=intercept)

        if base_name == "quadra_trend":
            a = self.a if self.a is not None else defaults["a"]
            b = self.b if self.b is not None else defaults["b"]
            c = self.c if self.c is not None else defaults["c"]
            return generate_quadratic(n, a=a, b=b, c=c)

        if base_name == "expo_trend":
            a = self.a if self.a is not None else defaults["a"]
            b = self.b if self.b is not None else defaults["b"]
            return generate_exponential(n, a=a, b=b)

        raise ValueError(f"No generator registered for {base_name!r}")

    def _split(self, values: np.ndarray) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
        """
        Args:
            values: full series, shape (n_points,).

        Returns:
            train: shape (n_train,).
            val: shape (n_val,).
            test: shape (n_points - n_train - n_val,).
        """
        n = len(values)
        n_train = round(n * TRAIN_FRAC)
        n_val = round(n * VAL_FRAC)
        train = values[:n_train]
        val = values[n_train : n_train + n_val]
        test = values[n_train + n_val :]
        return train, val, test


def generate_all_datasets(n_points: int = N_POINTS, seed: Optional[int] = None) -> dict[str, TimeSeriesDataset]:
    """
    Args:
        n_points: total number of time steps for every dataset.
        seed: seed for the noise random generator, for reproducibility.

    Returns:
        dict mapping each of `ALL_DATASET_NAMES` (20 datasets: the 5 base
        series plus their noisy counterparts at each of `SNR_LEVELS_DB`)
        to its `TimeSeriesDataset`.
    """
    return {name: TimeSeriesDataset(name=name, n_points=n_points, seed=seed) for name in ALL_DATASET_NAMES}
